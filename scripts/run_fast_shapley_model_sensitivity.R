#!/usr/bin/env Rscript
# Reuses existing NFZ GAM fits. NEVER refits GAMs.
# Exact 4-factor scenario mapping from R/03_predict_helpers.R.
suppressPackageStartupMessages({library(data.table); library(mgcv)})
source('R/99_load_all.R')
cfg <- load_config('config.R')
OUT <- 'output/pilot_fast_shapley_sensitivity'
dir.create(OUT,recursive=TRUE,showWarnings=FALSE)
DATA_PATH <- 'output/rds/aggregated_data.rds'
CHAIN_PATH <- 'output/rds/model_fit.rds'
if (!file.exists(CHAIN_PATH)) stop('Need the ORIGINAL full model chain at ',CHAIN_PATH,' (patients, provision, value). No refitting.')
if (!file.exists(DATA_PATH)) stop('Need original aggregated cells at ',DATA_PATH,'. No refitting.')
chain <- readRDS(CHAIN_PATH)
if (!all(c('m_pat','m_prov','m_val') %in% names(chain))) stop('Saved original model_fit.rds lacks chain models.')
d <- as.data.table(readRDS(DATA_PATH))
need <- c('year','code','sex','age_group','pop','n_patients','n_provision','value')
if(length(setdiff(need,names(d))))stop('Missing data variables: ',paste(setdiff(need,names(d)),collapse=', '))
if(anyDuplicated(d[,.(code,year,sex,age_group)])) stop('Duplicate year/code/sex/age cells: do not aggregate implicitly.')
base_yr <- as.integer(cfg$data$baseline_year)
last_yr <- max(as.integer(d$year))
if(base_yr==last_yr)stop('Only one year')
# Same original scenario_from_set mapping: baseline rows when N=off, target rows when N=on.
# Do not join population between endpoint years: their observed cell sets may differ.
d[, `:=`(year=as.integer(year),code=factor(code),sex=factor(sex),age_group=factor(age_group))]
d[, year_num:=as.numeric(year)]
d[, sex_age:=interaction(sex,age_group,drop=TRUE)]
d[, code_age:=interaction(code,age_group,drop=TRUE,lex.order=TRUE)]
d[, code_sex:=interaction(code,sex,drop=TRUE,lex.order=TRUE)]
d[, year_c:=year_num-mean(range(year_num))]
d[, log_pop_offset:=base::log(pmax(as.numeric(pop),cfg$model$eps_offset))]
d[, log_pop:=base::log(pmax(as.numeric(pop),cfg$model$eps_offset))]
# Population predictor defined and centered exactly as in model-grid pilot.
d[, log_pop_c:=log_pop-mean(log_pop),by=.(year,sex,age_group)]
d[, pandemic_c:=as.numeric(year_num %in% c(2020,2021))-2/data.table::uniqueN(year_num)]
d[, pandemic_c:=pandemic_c-mean(pandemic_c),by=code]
# For counterfactual states, use training-year/sex/age centering constants.
cent <- d[,.(center=mean(log_pop)),by=.(year,sex,age_group)]
setkey(cent,year,sex,age_group)
pand_unit <- d[,.(unit_pandemic_mean=mean(as.numeric(year_num %in% c(2020,2021))-2/data.table::uniqueN(year_num))),by=code]
setkey(pand_unit,code)
# Load saved model candidates. These paths are those generated by prior pilot scripts.
paths <- list(
 RE='output/pilot_mrf_patients/patient_models_RE_MRF.rds',
 RE_AGE_SLOPE='output/pilot_patients_random_slopes/models_random_slopes.rds',
 SEX='output/pilot_patients_missing_terms/model_cache/model_SEX.rds',
 ALL_K7='output/pilot_patients_missing_terms/model_cache/model_ALL_K7.rds')
load_candidate <- function(nm,path){
 if(nm=='RE'){
  if(file.exists(path))return(readRDS(path)$RE)
  return(chain$m_pat)
 }
 if(!file.exists(path))stop('Missing saved model ',nm,': ',path)
 z<-readRDS(path)
 if(nm=='RE_AGE_SLOPE')z<-z$RE_AGE_SLOPE
 if(!inherits(z,'gam'))stop('Invalid GAM object for ',nm)
 z
}
mods <- lapply(names(paths),function(nm)load_candidate(nm,paths[[nm]]));names(mods)<-names(paths)
for(nm in names(mods)){
 m<-mods[[nm]]
 if(!inherits(m,'gam')) stop('Not a GAM: ',nm)
 if(nobs(m)!=nrow(d) || length(m$y)!=nrow(d) ||
    !isTRUE(all.equal(as.numeric(m$y),as.numeric(d$n_patients),tolerance=0,check.attributes=FALSE)))
    stop('Input rows / order disagree with the saved GAM for ',nm,'. Stop to avoid invalid Shapley.')
}
# Protect against different factor levels across fit and prediction data.
# NOTE this study has 42,556 original analytical cells and 112 demographic/time slices.
# Rebuild all derived vars for every counterfactual, including independent N/PI year selections.
prep_patient_cf <- function(df,yr,pop){
 x <- as.data.table(data.table::copy(df))
 x[, `:=`(year=as.integer(yr),year_num=as.numeric(yr),pop=as.numeric(pop))]
 x[, year_c:=year_num-mean(range(d$year_num))]
 x[, log_pop_offset:=base::log(pmax(pop,cfg$model$eps_offset))]
 x[, log_pop:=base::log(pmax(pop,cfg$model$eps_offset))]
 # Center against training population distribution of the patient-model YEAR, not against the counterfactual mixture.
 z <- cent[.(as.integer(yr),x$sex,x$age_group), on=.(year,sex,age_group)]$center
 if(length(z)!=nrow(x)||anyNA(z))stop('Cannot map population centering constants')
 x[,log_pop_c:=log_pop-z]
 u <- pand_unit[.(x$code),on='code']$unit_pandemic_mean
 if(length(u)!=nrow(x)||anyNA(u))stop('Cannot map pandemic centering constants')
 x[,pandemic_c:=as.numeric(yr %in% c(2020,2021))-2/data.table::uniqueN(d$year)-u]
 x
}
# The original pilot calculated pandemic_c by two consecutive assignments:
# base indicator minus 2/years, then minus per-code mean of that centered indicator.
# Equivalent counterfactual is indicator - original per-code mean of indicator.
mk_state <- function(active){
 # IMPORTANT: the ORIGINAL R/03_predict_helpers.R scenario_from_set()
 # uses the target year rows for N=on, and baseline year rows for N=off.
 # It does NOT align or join 2018 population to 2024 rows. This also
 # handles the unequal number of observed cells across endpoint years.
 useN <- 'N' %in% active
 x <- data.table::copy(d[year == if (useN) last_yr else base_yr])
 stopifnot(nrow(x) > 0L, !anyNA(x$pop), length(x$pop)==nrow(x))
 list(frame=x, pop=as.numeric(x$pop),
      yr_pat=if ('PI' %in% active) last_yr else base_yr,
      yr_prov=if ('LAMBDA' %in% active) last_yr else base_yr,
      yr_val=if ('KAPPA' %in% active) last_yr else base_yr)
}

# This call exactly matches original scenario_from_set's choice of target/base rows, pop, and year toggles.
scenario_value <- function(patient_model, active){
 a<-mk_state(active)
 x<-prep_patient_cf(a$frame,a$yr_pat,a$pop)
 ph<-as.numeric(stats::predict(patient_model,newdata=x,type='response'))
 if(length(ph)!=nrow(x)||any(!is.finite(ph)))stop('Bad patient prediction')
 x[,`:=`(year=as.integer(a$yr_prov),year_num=as.numeric(a$yr_prov),n_patients=ph)]
 qh<-as.numeric(stats::predict(chain$m_prov,newdata=x,type='response'))
 if(length(qh)!=nrow(x)||any(!is.finite(qh)))stop('Bad provision prediction')
 x[,`:=`(year=as.integer(a$yr_val),year_num=as.numeric(a$yr_val),n_provision=qh)]
 vh<-as.numeric(stats::predict(chain$m_val,newdata=x,type='response'))
 if(length(vh)!=nrow(x)||any(!is.finite(vh)))stop('Bad value prediction')
 sum(ifelse(qh<=0,0,vh))
}
comps<-c('N','PI','LAMBDA','KAPPA')
perms<-combinat_permutations(comps)
subsets<-unlist(lapply(0:4,function(i)combn(comps,i,simplify=FALSE)),recursive=FALSE)
key <- function(v)if(!length(v))'EMPTY' else paste(comps[comps%in%v],collapse='_')
# Fast endpoint-only patient indicators: model prediction in natural observed year / population.
byyear <- list(); bydem <- list()
cat('Existing GAMs only; no refitting. 16 scenario evaluations per model.\n')
pb<-utils::txtProgressBar(min=0,max=length(mods)*17,style=3,width=35); step<-0
for(nm in names(mods)){
 m<-mods[[nm]]
 for(yy in c(base_yr,last_yr)){
  z<-d[year==yy]
  xp<-prep_patient_cf(z,yy,z$pop)
  yp<-as.numeric(stats::predict(m,newdata=xp,type='response'))
  o<-data.table(model=nm,year=yy,observed_patients=sum(z$n_patients),pred_patients=sum(yp),
   population=sum(z$pop),observed_reach=sum(z$n_patients)/sum(z$pop),model_reach=sum(yp)/sum(z$pop))
  byyear[[length(byyear)+1L]]<-o
  bydem[[length(bydem)+1L]]<-data.table(model=nm,year=yy,sex=z$sex,age_group=z$age_group,
   observed=z$n_patients,predicted=yp,pop=z$pop)[,.(observed=sum(observed),predicted=sum(predicted),population=sum(pop)),by=.(model,year,sex,age_group)]
 }
 step<-step+1;utils::setTxtProgressBar(pb,step)
 # Cache scenario values on disk, so rerun after interruption does not recompute completed predictions.
 cp<-file.path(OUT,paste0('cache_scenarios_',nm,'.rds'))
 vals<-if(file.exists(cp))tryCatch(readRDS(cp),error=function(e)numeric()) else numeric()
 if(is.null(names(vals)))vals<-numeric()
 for(sb in subsets){
  k<-key(sb)
  if(!k%in%names(vals) || !is.finite(vals[[k]])){
   vals[k]<-scenario_value(m,sb)
   saveRDS(vals,cp)
  }
  step<-step+1;utils::setTxtProgressBar(pb,step)
 }
 if(length(vals)!=16L)stop('Expected exactly 16 counterfactual values for ',nm)
 mat<-matrix(0,nrow=length(perms),ncol=length(comps),dimnames=list(NULL,comps))
 for(i in seq_along(perms)){
  active<-character();prev<-vals[[key(active)]]
  for(comp in perms[[i]]){
   active<-c(active,comp);curr<-vals[[key(active)]]
   mat[i,comp]<-curr-prev;prev<-curr
  }
 }
 sv<-colMeans(mat)
 res<-data.table(model=nm,baseline_year=base_yr,comparison_year=last_yr,
  model_total_2018=vals[['EMPTY']],model_total_2024=vals[[key(comps)]],
  total_change=vals[[key(comps)]]-vals[['EMPTY']],
  N_effect=sv[['N']],PI_effect=sv[['PI']],LAMBDA_effect=sv[['LAMBDA']],KAPPA_effect=sv[['KAPPA']],
  additivity_residual=(vals[[key(comps)]]-vals[['EMPTY']])-sum(sv))
 if(!exists('results'))results<-list()
 results[[nm]]<-res
 fwrite(rbindlist(results),file.path(OUT,'TABLE_shapley_model_sensitivity.csv'))
}
close(pb)
sh<-rbindlist(results)
ref<-sh[model=='RE']
for(cc in c('total_change','N_effect','PI_effect','LAMBDA_effect','KAPPA_effect')) sh[,paste0('delta_',cc,'_vs_RE'):=get(cc)-ref[[cc]]]
fwrite(sh,file.path(OUT,'TABLE_shapley_model_sensitivity.csv'))
fwrite(rbindlist(byyear),file.path(OUT,'TABLE_patient_endpoint_totals.csv'))
fwrite(rbindlist(bydem),file.path(OUT,'TABLE_patient_demographic_endpoints.csv'))
# Metadata and checkpoint audit
fwrite(data.table(model=names(mods),formula=vapply(mods,function(z)paste(deparse(formula(z)),collapse=' '),character(1))),file.path(OUT,'TABLE_model_formulas.csv'))
cat('\nSaved:',OUT,'\n');print(sh[,.(model,total_change,N_effect,PI_effect,LAMBDA_effect,KAPPA_effect,additivity_residual)])
